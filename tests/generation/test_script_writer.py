@pytest.mark.parametrize(
    ("style", "filename"),
    [
        ("pom", "pages_selenium.py"),
        ("test", "test_healix_selenium.py"),
        ("action", "actions_selenium.py"),
    ],
)
def test_output_directory_gets_a_file_named_for_its_style(manifest, tmp_path, style, filename):
    out = tmp_path / "scripts"
    script = ScriptGenerator(manifest, record_fingerprints=False).to_selenium(style, output=out)
    assert script.file_path == out / filename
    assert (out / filename).read_text() == script.source
    assert not [p for p in out.iterdir() if p.name.endswith(".tmp")]


def test_output_can_name_the_file_itself(manifest, tmp_path):
    target = tmp_path / "deep" / "my_pages.py"
    script = ScriptGenerator(manifest, record_fingerprints=False).to_playwright(output=target)
    assert script.file_path == target and target.exists()


def test_a_script_generated_event_matches_the_shared_schema(manifest, tmp_path):
    events = []
    script = ScriptGenerator(manifest, record_fingerprints=False, on_event=events.append)
    result = script.to_playwright("pom", output=tmp_path)
    assert result.element_count == 11
    [event] = events
    assert event["event"] == "script_generated" and event["run_id"] == "run-1"
    assert set(event["data"]) == set(EVENT_DATA_FIELDS["script_generated"])
    assert event["data"] == {
        "backend": "playwright",
        "style": "pom",
        "file_path": str(result.file_path),
        "element_count": 11,  # 5 on the login page, 5 on the order form, 1 link on the home page
    }


def test_the_event_goes_to_a_webhook_too(manifest, webhook_receiver):
    ScriptGenerator(
        manifest, record_fingerprints=False, webhook_url=webhook_receiver.url
    ).to_playwright()
    [payload] = webhook_receiver.payloads
    assert payload["event"] == "script_generated" and payload["data"]["file_path"] is None


# --- a script pointed at a database with nothing in it ---------------------------------------- #


def test_a_database_with_no_fingerprints_for_the_pages_is_warned_about(manifest, tmp_path):
    """The crawl recorded into one database and the script points at another: say so now."""
    missing = generate(
        manifest, fingerprint_db=tmp_path / "nowhere.db"
    )  # record_fingerprints=False
    assert len(missing.warnings) == 1 and "no fingerprints" in missing.warnings[0]
    assert not (tmp_path / "nowhere.db").exists()  # checking must not create it

    from healix import SQLiteFingerprintStore

    with SQLiteFingerprintStore(tmp_path / "empty.db"):
        pass
    assert generate(manifest, fingerprint_db=tmp_path / "empty.db").warnings


def test_no_warning_once_fingerprints_exist_or_are_being_recorded(manifest, tmp_path):
    db = tmp_path / "fp.db"
    recorded = ScriptGenerator(manifest, fingerprint_db=db).to_playwright()
    assert recorded.warnings == ()
    assert generate(manifest, fingerprint_db=db).warnings == ()  # already there, not re-recorded


def test_a_database_url_is_not_connected_to_just_to_warn(manifest):
    url = "postgresql://healix:pw@unreachable.invalid:5432/healix"
    assert generate(manifest, fingerprint_db=url).warnings == ()
