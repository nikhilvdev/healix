def test_pom_has_a_class_per_page_and_a_method_per_element(manifest):
    source = generate(manifest, style="pom").source
    for name in ("class LoginPage:", "class OrdersNewPage:", "class HomePage:"):
        assert name in source
    for method in (
        "def fill_login_username(",
        "def fill_password(",
        "def click_remember(",
        "def click_sign_in(",
        "def click_forgot_password(",
        "def fill_email(",
        "def click_save_order(",
    ):
        assert method in source
    assert "def open(self)" in source


def test_controls_that_cannot_be_typed_into_are_located_not_filled(manifest):
    source = generate(manifest, style="pom").source
    assert "def locate_locked(" in source  # read-only
    assert "def locate_frozen(" in source  # disabled
    assert "def fill_locked" not in source and "def fill_frozen" not in source


def test_test_style_asserts_and_never_types_or_clicks(manifest):
    source = generate(manifest, style="test").source
    assert "def test_login(" in source and "def test_orders_new(" in source
    assert "assert" in source and "pytest" in source
    assert ".write(" not in source and ".click(" not in source
    assert 'path.rstrip("/") == "/orders/new"' in source


def test_action_style_fills_then_submits_and_asserts_nothing(manifest):
    source = generate(manifest, style="action").source
    assert not [n for n in ast.walk(ast.parse(source)) if isinstance(n, ast.Assert)]
    login = source[source.index("def run_login") : source.index("def run_orders_new")]
    assert login.index(".write(") < login.index(".click(")
    assert "textbox:login-username" in login and "button:sign-in" in login
    assert "checkbox:remember" not in login  # only inputs are filled, and the submit is clicked
    assert "def run_home" not in source  # a page with nothing to fill has nothing to do


