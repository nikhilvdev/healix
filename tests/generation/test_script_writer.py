def test_fingerprints_are_recorded_for_the_scripts_to_heal_against(manifest, tmp_path):
    from healix import SQLiteFingerprintStore

    db = tmp_path / "fp.db"
    ScriptGenerator(manifest, fingerprint_db=db).to_playwright(style="pom")
    with SQLiteFingerprintStore(db) as store:
        roles = {f.element_role for f in store.fingerprints(f"{BASE}/login")}
    assert roles == {
        "textbox:login-username",
        "textbox:password",
        "checkbox:remember",
        "button:sign-in",
        "link:forgot-password",
    }


def test_recording_can_be_switched_off(manifest, tmp_path):
    db = tmp_path / "fp.db"
    generate(manifest, fingerprint_db=db)  # record_fingerprints=False in the helper
    assert not db.exists()


# --- hostile page content ---------------------------------------------------------------------- #


def test_text_from_the_page_cannot_inject_code(tmp_path):
    hostile = 'x"); import os; os.system("boom"); ("'
    elements = [
        el("input", name="q", type="text", aria_label=hostile, data_testid=hostile),
        el("button", text=hostile, type="submit"),
    ]
    url = f"{BASE}/a\"b'c\\d\n/e"
    manifest = write_run(tmp_path, {url: ("form\nimport os", elements)})
    for backend, style in COMBINATIONS:
        source = generate(manifest, backend, style).source
        tree = ast.parse(source)
        calls = [
            n.func.attr
            for n in ast.walk(tree)
            if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
        ]
        assert "system" not in calls
        assert imports_of(source) <= SAFE_IMPORTS


