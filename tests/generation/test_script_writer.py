def generate(manifest, backend="playwright", style="pom", **kwargs):
    kwargs.setdefault("record_fingerprints", False)
    return ScriptGenerator(manifest, **kwargs).generate(backend, style)


def imports_of(source):
    tree = ast.parse(source)
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(a.name.split(".")[0] for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0:
            found.add((node.module or "").split(".")[0])
    return found


# --- every backend and style ------------------------------------------------------------------- #


@pytest.mark.parametrize(("backend", "style"), COMBINATIONS)
def test_every_backend_and_style_gives_valid_python(manifest, backend, style):
    script = generate(manifest, backend, style)
    ast.parse(script.source)
    assert (script.backend, script.style) == (backend, style)
    assert script.file_path is None  # nothing is written unless asked
    assert "generated by Healix" in script.source


@pytest.mark.parametrize(("backend", "style"), COMBINATIONS)
def test_generated_code_goes_through_healix_and_never_imports_a_browser_library(
    manifest, backend, style
):
    imported = imports_of(generate(manifest, backend, style).source)
    assert "healix" in imported
    assert not imported & {"playwright", "selenium"}


def test_the_backend_only_changes_which_adapter_is_used(manifest):
    playwright = generate(manifest, "playwright", "action").source
    selenium = generate(manifest, "selenium", "action").source
    assert "PlaywrightDriverAdapter" in playwright and "Selenium" not in playwright
    assert "SeleniumDriverAdapter" in selenium and "Playwright" not in selenium
    assert playwright.replace("Playwright", "X").count("run_login") == selenium.count("run_login")


def test_output_is_deterministic(manifest):
    assert generate(manifest).source == generate(manifest).source


