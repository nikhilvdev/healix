def test_sources_a_generator_accepts(tmp_path):
    manifest_path = write_run(tmp_path)
    manifest = Manifest.load(manifest_path)
    from_path = generate(manifest_path).source
    assert generate(manifest, base_dir=tmp_path).source == from_path
